const Sprite* findSprite(const char* id) {
  for (const Sprite& s : SPRITES)
    if (strcmp(s.id, id) == 0) return &s;
  return nullptr;
}

size_t spriteCount() { return sizeof(SPRITES) / sizeof(SPRITES[0]); }
const Sprite& spriteAt(size_t i) { return SPRITES[i]; }
